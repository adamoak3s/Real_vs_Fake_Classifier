"""Rebuild the Task 6 evaluation sample from the dataset.

Run it after Prepare_data.ipynb has created data/train and data/test:

    python prepare_task_6_sample.py

It creates, inside the project folder:

    data/task_6_sample/images/                    200 test images (100 REAL, 100 FAKE), shuffled, renamed
                                                  img_001..img_200 and enlarged 8x (32x32 -> 256x256,
                                                  nearest-neighbor, so no pixels are blended)
    data/task_6_sample/sheets/                    8 contact sheets of 25 numbered images, for chat tools
    data/task_6_sample/PROMPT.txt                 the prompt given to every chat tool
    data/task_6_sample/teachable_machine_train/   500 REAL + 500 FAKE training images, enlarged the same way
    results/task_6/answer_key.csv                 id, true label, source file

The selection is fixed by the seeds below, so the same dataset always gives the same sample.
results/task_6/answer_key.csv is kept in the repository: if it already exists, the script checks
that the sample it just drew matches it, and stops if it doesn't (a mismatch means the dataset's
file names differ from the original run, so the saved predictions would no longer line up).

Requires only Pillow. Options: --out and --results change the output folders, --force overwrites
a mismatching answer key.
"""
import argparse
import csv
import os
import random
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SAMPLE_SEED = 6          # which test images are drawn, and their order
TM_SEED = 66             # which training images go to Teachable Machine
N_PER_CLASS = 100        # test images per class
TM_PER_CLASS = 500       # Teachable Machine training images per class
SCALE = 8                # 32 px -> 256 px
PER_SHEET, COLS = 25, 5
CLASSES = ["REAL", "FAKE"]

PROMPT = """The attached contact sheet shows 25 numbered images. Each one is a 32x32-pixel image that has been enlarged 8x without smoothing. Some are real photographs and some were generated by an AI image model.

For every numbered image, decide whether it is REAL (a photograph) or FAKE (AI-generated). You must give an answer for every image, even if you are unsure.

Reply with one line per image, in this exact format and nothing else:
<number>,<REAL or FAKE>
"""


def find_project_root():
    here = Path(__file__).resolve().parent
    for d in [here, *here.parents]:
        if (d / "data" / "train").is_dir() and (d / "data" / "test").is_dir():
            return d
    sys.exit("Couldn't find the project folder (one that contains data/train and data/test). "
             "Run Prepare_data.ipynb first.")


def enlarge(path):
    im = Image.open(path).convert("RGB")
    return im.resize((im.width * SCALE, im.height * SCALE), Image.NEAREST)


def label_font():
    for name in ("DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
                 "Arial Bold.ttf", "arialbd.ttf"):
        try:
            return ImageFont.truetype(name, 26)
        except OSError:
            pass
    return ImageFont.load_default()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, help="sample folder (default: data/task_6_sample)")
    ap.add_argument("--results", type=Path, help="folder for answer_key.csv (default: results/task_6)")
    ap.add_argument("--force", action="store_true", help="overwrite an answer key that doesn't match")
    args = ap.parse_args()

    root = find_project_root()
    out = args.out or root / "data" / "task_6_sample"
    results = args.results or root / "results" / "task_6"

    # 1. Draw the test sample. File lists are sorted so the draw doesn't depend on the file system.
    rng = random.Random(SAMPLE_SEED)
    items = []
    for label in CLASSES:
        files = sorted(os.listdir(root / "data" / "test" / label))
        for name in rng.sample(files, N_PER_CLASS):
            items.append((label, f"data/test/{label}/{name}"))
    rng.shuffle(items)
    rows = [(i, label, src) for i, (label, src) in enumerate(items, 1)]

    # 2. Check against the answer key in the repository, then write it.
    key_path = results / "answer_key.csv"
    if key_path.exists():
        with open(key_path, newline="") as fh:
            old = [(int(r["id"]), r["label"], r["source"]) for r in csv.DictReader(fh)]
        if old != rows and not args.force:
            sys.exit(f"STOPPED: the sample drawn from this dataset does not match {key_path}.\n"
                     "The dataset's file names probably differ from the original run. Nothing was written.\n"
                     "Use --force to replace the answer key (the saved predictions will then no longer apply).")
        print("answer key matches the existing one" if old == rows else "answer key replaced (--force)")
    (results / "predictions").mkdir(parents=True, exist_ok=True)
    with open(key_path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "label", "source"])
        w.writerows(rows)

    # 3. Enlarged images.
    (out / "images").mkdir(parents=True, exist_ok=True)
    big = []
    for i, _, src in rows:
        im = enlarge(root / src)
        im.save(out / "images" / f"img_{i:03d}.png")
        big.append(im)

    # 4. Contact sheets.
    (out / "sheets").mkdir(exist_ok=True)
    font = label_font()
    size, pad, top = 32 * SCALE, 14, 34
    for start in range(0, len(big), PER_SHEET):
        chunk = big[start:start + PER_SHEET]
        n_rows = (len(chunk) + COLS - 1) // COLS
        sheet = Image.new("RGB", (COLS * (size + pad) + pad, n_rows * (size + pad + top) + pad), "white")
        draw = ImageDraw.Draw(sheet)
        for j, im in enumerate(chunk):
            x = pad + (j % COLS) * (size + pad)
            y = pad + (j // COLS) * (size + pad + top)
            draw.text((x, y), str(start + j + 1), fill="black", font=font)
            sheet.paste(im, (x, y + top))
        sheet.save(out / "sheets" / f"sheet_{start // PER_SHEET + 1}.png")

    # 5. Prompt for the chat tools.
    (out / "PROMPT.txt").write_text(PROMPT)

    # 6. Training images for Teachable Machine (from data/train, so none are in the test sample).
    rng = random.Random(TM_SEED)
    for label in CLASSES:
        folder = out / "teachable_machine_train" / label
        folder.mkdir(parents=True, exist_ok=True)
        files = sorted(os.listdir(root / "data" / "train" / label))
        for i, name in enumerate(rng.sample(files, TM_PER_CLASS), 1):
            enlarge(root / "data" / "train" / label / name).save(folder / f"{label.lower()}_{i:03d}.png")

    print(f"wrote {len(rows)} sample images, {(len(big) + PER_SHEET - 1) // PER_SHEET} sheets and "
          f"{TM_PER_CLASS * len(CLASSES)} Teachable Machine training images to {out}")
    print(f"answer key: {key_path}")


if __name__ == "__main__":
    main()
